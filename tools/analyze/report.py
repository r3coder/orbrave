"""Per-genre data sheets from the analyzer output.

    analysis/out/<genre>/*.json  ->  analysis/genres/<genre>/data.md + figures/

data.md is regenerated on every run; the hand-written analysis lives next to it in README.md.

    tools/analyze/.venv/Scripts/python tools/analyze/report.py
"""
import json
import shutil
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'analysis' / 'out'
DOCS = ROOT / 'analysis' / 'genres'
SOURCES = ROOT / 'analysis' / 'tracks' / 'sources.json'
LAYERS = ['drums', 'bass', 'other', 'vocals']
DEGREE = ['1', 'b2', '2', 'b3', '3', '4', 'b5', '5', 'b6', '6', 'b7', '7']


def med(v, d=1):
    v = [x for x in v if x is not None and np.isfinite(x)]
    return round(float(np.median(v)), d) if v else None


def fmt(v, unit=''):
    return '—' if v is None else f'{v}{unit}'


def presence(t, n, thr=-15):
    a = np.array(t['activity'][LAYERS.index(n)])
    return float(np.mean(a > thr))


def entry_bar(t, n, thr=-12):
    a = np.array(t['activity'][LAYERS.index(n)])
    on = np.where(a > thr)[0]
    return int(on[0]) if len(on) else None


def stem_profile(t, n):
    """Median timbre of one stem over the bars where it plays."""
    a = np.array(t['activity'][LAYERS.index(n)])
    tim = t['timbre'][n]
    sel = a > -15
    pick = lambda k: med([v for v, s in zip(tim[k], sel) if s and v is not None], 3)
    return {'brightness': pick('centroid'), 'onsets': pick('onsets'), 'sustain': pick('sustain'), 'noisy': pick('flatness')}


def character(p, n):
    """Plain-language label from timbre numbers (rough, for reading the tables)."""
    if p['brightness'] is None:
        return '—'
    words = []
    if n == 'bass':
        words.append('sub-heavy' if p['brightness'] < 150 else ('mid bass' if p['brightness'] > 400 else 'round'))
    else:
        b = p['brightness']
        words.append('dark' if b < 1500 else ('bright' if b > 4000 else 'mid'))
    if p['sustain'] is not None:
        words.append('sustained' if p['sustain'] > .45 else ('plucky/stabby' if p['sustain'] < .2 else 'mixed'))
    if p['onsets'] is not None and n != 'drums':
        words.append('busy' if p['onsets'] > 8 else ('sparse' if p['onsets'] < 3 else ''))
    if p['noisy'] is not None and p['noisy'] > .1:
        words.append('noisy')
    return ', '.join(w for w in words if w)


def title_of(sources, genre, fname):
    for s in sources.get(genre, []):
        if Path(s.get('local', '')).name == fname:
            return f"{s['creator'] or '—'} – {s['title']}", s
    return fname, None


def genre_sheet(genre, gdir, sources):
    prof = json.loads((gdir / 'profile.json').read_text(encoding='utf-8'))
    tracks = [json.loads(p.read_text(encoding='utf-8')) for p in sorted(gdir.glob('*.json')) if p.name != 'profile.json']
    dst = DOCS / genre
    fig = dst / 'figures'
    fig.mkdir(parents=True, exist_ok=True)
    shutil.copy(gdir / 'profile.png', fig / 'profile.png')
    L = [f'# {genre} — data sheet', '',
         f'Auto-generated by `tools/analyze/report.py` from {len(tracks)} Creative Commons tracks '
         '(list and licenses: [analysis/tracks/SOURCES.md](../../tracks/SOURCES.md)). Hand-written reading: [README.md](README.md).', '',
         '![genre profile](figures/profile.png)', '']

    # ---- tracks
    L += ['## Tracks', '', '| # | Track | BPM | Key | Length | Bars | Swing | Pumping bass/other (dB) | Harmonic bars |',
          '|---|---|---|---|---|---|---|---|---|']
    for i, t in enumerate(tracks, 1):
        name, _ = title_of(sources, genre, t['file'].replace('.json', ''))
        m, s = divmod(int(t['duration']), 60)
        L.append(f"| {i} | {name} | {t['bpm']}{'' if t['steadyTempo'] else ' (drifts)'} | {t['key']['tonic']} {t['key']['mode']} "
                 f"| {m}:{s:02d} | {t['bars']} | {fmt(t['swing']['drums'], '%')} | {fmt(t['pumping']['bass'])} / {fmt(t['pumping']['other'])} "
                 f"| {int(round(t['harmonicBars'] * 100))}% |")
    L += ['', f"Median: **{prof['bpm']['median']} BPM** (range {prof['bpm']['min']}–{prof['bpm']['max']}), "
          f"minor keys {int(prof['minorRatio'] * 100)}%, drum swing {fmt(prof['swing']['drums'], '%')}, "
          f"sidechain pumping bass {fmt(prof['pumping']['bass'])} dB / other {fmt(prof['pumping']['other'])} dB, mix {prof['loudness']['mixMedian']} LUFS.", '',
          '_Swing: lateness of off-16ths in % of a 16th (0 straight, ~33 triplet). Pumping: level dip folded over one beat (≥6 dB is audible ducking). '
          'Harmonic bars: bars where a clear triad was found._', '']

    # ---- instrumentation
    L += ['## Instrumentation (stems)', '',
          'Level = loudness vs the drum stem (LU). Present = share of bars the stem plays. Brightness = spectral centroid while playing. '
          'Onsets = note/hit starts per bar. Sustain = share of each bar above half its peak (pads high, stabs/plucks low).', '',
          '| Stem | Level vs drums | Present | Enters at bar | Brightness | Onsets/bar | Sustain | Reads as |', '|---|---|---|---|---|---|---|---|']
    for n in LAYERS:
        ps = [stem_profile(t, n) for t in tracks]
        agg = {k: med([p[k] for p in ps], 3) for k in ('brightness', 'onsets', 'sustain', 'noisy')}
        L.append(f"| {n} | {fmt(prof['relativeToDrums'][n]['median'])} | {int(round(np.mean([presence(t, n) for t in tracks]) * 100))}% "
                 f"| {fmt(med([entry_bar(t, n) for t in tracks], 0))} | {fmt(agg['brightness'] and int(agg['brightness']), ' Hz')} "
                 f"| {fmt(agg['onsets'] and round(agg['onsets'], 1))} | {fmt(agg['sustain'] and round(agg['sustain'], 2))} | {character(agg, n)} |")
    L += ['', '_`other` = everything pitched that is not bass or voice: pads, chords, leads, arps, FX. `vocals` also catches vocal-like leads and chops._', '']

    # ---- rhythm
    skipped = [t['file'] for t in tracks if t['file'] not in prof.get('gridTracks', [t['file'] for t in tracks])]
    L += ['## Rhythm grid', '', '16 steps per bar; `x` = hit in ≥60% of bars, `o` = ≥25%, `.` = rarely. Genre average, then per track.'
          + (f" The average leaves out {len(skipped)} track(s) whose bar grid did not lock (kick smeared over every step): "
             + ', '.join(f'`{s}`' for s in skipped) if skipped else ''), '',
          '```', '           1   2   3   4   (beats)', '           |...|...|...|...']
    for r in ('kick', 'snare', 'hats', 'bass'):
        L.append(f"{r:10} {prof['grid'][r]['pattern']}   {prof['grid'][r]['hitsPerBar']}/bar")
    L += ['```', '', '<details><summary>per track</summary>', '', '```']
    for t in tracks:
        L.append(t['file'][:60])
        for r in ('kick', 'snare', 'hats', 'bass'):
            L.append(f"  {r:6} {t['grid'][r]['pattern']}  {t['grid'][r]['hitsPerBar']}/bar")
    L += ['```', '', '</details>', '']

    # ---- bass & harmony
    deg = prof['bass']['degrees']
    top = sorted(range(12), key=lambda i: -deg[i])[:5]
    L += ['## Bass and harmony', '',
          f"- Bass notes per bar: **{prof['bass']['notesPerBar']}**, repeated-note ratio {prof['bass']['repeatRatio']}, octave jumps {prof['bass']['octaveJumpRatio']}",
          f"- Bass scale degrees (share of notes): " + ', '.join(f'{DEGREE[i]} {int(deg[i] * 100)}%' for i in top),
          f"- Keys: " + ', '.join(f'{k} ×{v}' for k, v in sorted(prof['keys'].items(), key=lambda kv: -kv[1])),
          f"- Bars with a clear triad: {int(round((prof['harmonicBars'] or 0) * 100))}% (low = atonal/one-note/percussive music)",
          '- Most common 4-bar chord loops (Roman numerals on the detected key; lower case = minor, N = no clear chord):', '']
    for k, c in prof['chordLoops']:
        L.append(f'  - `{k}` ×{c}')
    L.append('')

    # ---- form & flow
    L += ['## Form and flow', '',
          f"Sections per track: {prof['form']['sectionsPerTrack']}, first peak at bar {fmt(prof['form']['barsBeforeFirstPeak'])}. "
          'Typical section lengths (bars): ' + ', '.join(f"{k} {v['median']}" for k, v in prof['form']['sectionBars'].items()), '',
          'Per track: sections in order with the stems playing, their level (dB vs each stem\'s loud bars) and how the `other` stem changes '
          '(brightness ↑ = filter opening over the section).', '']
    for t in tracks:
        name, _ = title_of(sources, genre, t['file'])
        L += [f'### {name}', '', f"![{t['file']}](figures/{Path(t['file']).stem}.png)", '',
              '| Bars | Section | Length | drums | bass | other | vocals | other brightness | Chords |', '|---|---|---|---|---|---|---|---|---|']
        for s in t['sectionDetail']:
            st = s['stems']
            cell = lambda n: f"{st[n]['level']}" + ('' if st[n]['level'] > -15 else ' ·')
            o = st['other']
            br = '—'
            if 'brightness' in o:
                sl = o.get('brightnessSlope', 0)
                br = f"{o['brightness']} Hz" + (' ↑' if sl > .4 else (' ↓' if sl < -.4 else ''))
            L.append(f"| {s['start']}–{s['start'] + s['bars']} | {s['label']} | {s['bars']} ({s['seconds']}s) | {cell('drums')} | {cell('bass')} "
                     f"| {cell('other')} | {cell('vocals')} | {br} | `{s['chords']}` |")
        L.append('')
        shutil.copy(gdir / f"{Path(t['file']).stem}.png", fig / f"{Path(t['file']).stem}.png")
    L += ['_Levels: 0 = the stem at its loudest; `·` = below −15 dB, i.e. effectively out._', '']
    (dst / 'data.md').write_text('\n'.join(L), encoding='utf-8')
    return prof, tracks


def main():
    sources = json.loads(SOURCES.read_text(encoding='utf-8')) if SOURCES.exists() else {}
    DOCS.mkdir(parents=True, exist_ok=True)
    rows = []
    for gdir in sorted(p for p in OUT.iterdir() if p.is_dir() and (p / 'profile.json').exists()):
        prof, tracks = genre_sheet(gdir.name, gdir, sources)
        rows.append((gdir.name, prof, tracks))
        print(gdir.name, len(tracks))
    # cross-genre overview table
    L = ['# Cross-genre overview (auto)', '', '| Genre | Tracks | BPM | Minor | Swing | Kick | Snare | Hats | Bass notes/bar | bass / other / vocals vs drums (LU) | Pumping bass/other | First peak (bar) |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for g, p, ts in rows:
        rel = p['relativeToDrums']
        L.append(f"| [{g}]({g}/README.md) | {p['tracks']} | {p['bpm']['median']} | {int(p['minorRatio'] * 100)}% | {fmt(p['swing']['drums'], '%')} "
                 f"| `{p['grid']['kick']['pattern']}` | `{p['grid']['snare']['pattern']}` | `{p['grid']['hats']['pattern']}` | {p['bass']['notesPerBar']} "
                 f"| {fmt(rel['bass']['median'])} / {fmt(rel['other']['median'])} / {fmt(rel['vocals']['median'])} "
                 f"| {fmt(p['pumping']['bass'])} / {fmt(p['pumping']['other'])} | {fmt(p['form']['barsBeforeFirstPeak'])} |")
    (DOCS / 'overview-data.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print('written', DOCS)


if __name__ == '__main__':
    sys.exit(main())
